SELECT *
FROM meter_readings
WHERE units_kwh >
(
    SELECT AVG(units_kwh)
    FROM meter_readings
);

-- 3

SELECT
    flat_id,
    tower,
    bhk
FROM flats
WHERE flat_id IN
(
    SELECT flat_id
    FROM meter_readings
    GROUP BY flat_id
    HAVING SUM(bill_inr) >
    (
        SELECT
            SUM(bill_inr) /
            COUNT(DISTINCT flat_id)
        FROM meter_readings
    )
);

