USE society_db;

CREATE TABLE flats (
    flat_id INT PRIMARY KEY,
    tower CHAR(1),
    bhk INT
);

CREATE TABLE meter_readings (
    reading_id INT PRIMARY KEY,
    flat_id INT,
    reading_month DATE,
    units_kwh INT,
    bill_inr DECIMAL(10,2),
    FOREIGN KEY (flat_id) REFERENCES flats(flat_id)
);

